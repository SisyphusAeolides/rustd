//! `RustD` kernel command-line run generator.

use std::env;
use std::fs;
use std::os::unix::fs::symlink;
use std::path::{Path, PathBuf};

fn main() {
    if let Err(error) = run() {
        eprintln!("rustd-run-generator: {error}");
        std::process::exit(1);
    }
}

fn run() -> Result<(), String> {
    let args: Vec<_> = env::args_os().collect();
    let dest = match args.len() {
        2 | 4 => PathBuf::from(&args[1]),
        _ => return Err("Expected one or three generator output directories.".into()),
    };
    let cmdline = env::var("RUSTD_PROC_CMDLINE").ok().map_or_else(
        || fs::read_to_string("/proc/cmdline").unwrap_or_default(),
        |path| fs::read_to_string(path).unwrap_or_default(),
    );

    let (commands, success, failure) = parse_cmdline(&cmdline);
    if commands.is_empty() && success.is_none() && failure.is_none() {
        return Ok(());
    }
    fs::create_dir_all(&dest).map_err(|error| format!("{}: {error}", dest.display()))?;

    let mut service = String::from(
        "[Unit]\nDescription=RustD command from kernel command line\nDocumentation=man:rustd-run-generator(8)\nSourcePath=/proc/cmdline\n",
    );
    if success.as_deref() != Some("none") {
        service.push_str(&format!(
            "SuccessAction={}\n",
            success.as_deref().unwrap_or("exit")
        ));
    }
    if failure.as_deref() != Some("none") {
        service.push_str(&format!(
            "FailureAction={}\n",
            failure.as_deref().unwrap_or("exit")
        ));
    }
    service.push_str("\n[Service]\nType=oneshot\nStandardOutput=journal+console\n");
    for command in commands {
        service.push_str("ExecStart=");
        service.push_str(&escape_specifiers(&command));
        service.push('\n');
    }
    fs::write(dest.join("kernel-command-line.service"), service)
        .map_err(|error| error.to_string())?;
    fs::write(
        dest.join("kernel-command-line.target"),
        "# Automatically generated by rustd-run-generator\n\n[Unit]\nDescription=RustD command from kernel command line\nDocumentation=man:rustd-run-generator(8)\nSourcePath=/proc/cmdline\nRequires=kernel-command-line.service\nAfter=kernel-command-line.service\n",
    )
    .map_err(|error| error.to_string())?;
    replace_symlink("kernel-command-line.target", &dest.join("default.target"))
}

fn parse_cmdline(cmdline: &str) -> (Vec<String>, Option<String>, Option<String>) {
    let mut commands = Vec::new();
    let mut success = None;
    let mut failure = None;
    for item in cmdline.split_whitespace() {
        let (key, value) = item.split_once('=').unwrap_or((item, ""));
        match key.strip_prefix("rd.").unwrap_or(key) {
            "rustd.run" if !value.is_empty() => commands.push(value.to_owned()),
            "rustd.run_success_action" if !value.is_empty() => success = Some(value.to_owned()),
            "rustd.run_failure_action" if !value.is_empty() => failure = Some(value.to_owned()),
            _ => {}
        }
    }
    (commands, success, failure)
}

fn replace_symlink(target: &str, path: &Path) -> Result<(), String> {
    match fs::remove_file(path) {
        Ok(()) => {}
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
        Err(error) => return Err(error.to_string()),
    }
    symlink(target, path).map_err(|error| error.to_string())
}

fn escape_specifiers(value: &str) -> String {
    value.replace('%', "%%")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn specifier_escape() {
        assert_eq!(escape_specifiers("echo 100%"), "echo 100%%");
    }

    #[test]
    fn native_kernel_controls_are_parsed() {
        let (commands, success, failure) = parse_cmdline(
            "quiet rustd.run=/usr/bin/true rustd.run_success_action=reboot rustd.run_failure_action=poweroff",
        );
        assert_eq!(commands, vec!["/usr/bin/true"]);
        assert_eq!(success.as_deref(), Some("reboot"));
        assert_eq!(failure.as_deref(), Some("poweroff"));
    }

    #[test]
    fn initrd_native_kernel_controls_are_parsed() {
        let (commands, _, _) = parse_cmdline("rd.rustd.run=/usr/bin/true");
        assert_eq!(commands, vec!["/usr/bin/true"]);
    }

    #[test]
    fn systemd_kernel_controls_are_not_authoritative() {
        let (commands, success, failure) = parse_cmdline(
            "systemd.run=/usr/bin/false systemd.run_success_action=reboot systemd.run_failure_action=poweroff",
        );
        assert_eq!(commands, [] as [std::string::String; 0]);
        assert!(success.is_none());
        assert!(failure.is_none());
    }
}

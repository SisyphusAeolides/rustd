//! Generate native `RustD` mount/swap units from `/etc/fstab`.

use std::fmt::Write as _;
use std::fs;
use std::os::unix::fs::symlink;
use std::path::{Path, PathBuf};

use anyhow::{anyhow, Context};

fn main() {
    if let Err(error) = run() {
        eprintln!("rustd-fstab-generator: {error:#}");
        std::process::exit(1);
    }
}

fn run() -> anyhow::Result<()> {
    let args: Vec<PathBuf> = std::env::args_os().skip(1).map(PathBuf::from).collect();
    let normal = match args.as_slice() {
        [normal] | [_, normal, _] => normal,
        _ => {
            return Err(anyhow!(
                "expected one or three generator output directories"
            ))
        }
    };
    generate_fstab(Path::new("/etc/fstab"), normal)
}

fn generate_fstab(fstab: &Path, output: &Path) -> anyhow::Result<()> {
    let text = match fs::read_to_string(fstab) {
        Ok(text) => text,
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => return Ok(()),
        Err(error) => return Err(error).with_context(|| format!("read {}", fstab.display())),
    };
    fs::create_dir_all(output)?;

    for (line_number, raw) in text.lines().enumerate() {
        let line = raw.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let fields: Vec<String> = line.split_whitespace().map(unescape_fstab).collect();
        if fields.len() < 4 {
            return Err(anyhow!(
                "{}:{}: expected at least four fields",
                fstab.display(),
                line_number + 1
            ));
        }
        let what = &fields[0];
        let where_ = &fields[1];
        let fstype = &fields[2];
        let options = &fields[3];
        let option_set: Vec<&str> = options.split(',').collect();
        if option_set.contains(&"noauto") {
            continue;
        }

        if fstype == "swap" {
            write_swap(output, what, options, &option_set)?;
        } else if where_ != "/" {
            write_mount(output, what, where_, fstype, options, &option_set)?;
        }
    }
    Ok(())
}

fn write_mount(
    output: &Path,
    what: &str,
    where_: &str,
    fstype: &str,
    options: &str,
    option_set: &[&str],
) -> anyhow::Result<()> {
    let unit_name = path_unit_name(where_, ".mount")?;
    let filtered = filtered_options(options);
    let mut unit = format!(
        "# Generated by rustd-fstab-generator\n\
         [Unit]\nSourcePath=/etc/fstab\nBefore=local-fs.target\n\n\
         [Mount]\nWhat={what}\nWhere={where_}\n"
    );
    if fstype != "auto" {
        let _ = writeln!(unit, "Type={fstype}");
    }
    if !filtered.is_empty() && filtered != "defaults" {
        let _ = writeln!(unit, "Options={filtered}");
    }
    fs::write(output.join(&unit_name), unit)?;
    link_dependency(
        output,
        if option_set.contains(&"_netdev") {
            "remote-fs.target"
        } else {
            "local-fs.target"
        },
        if option_set.contains(&"nofail") {
            "wants"
        } else {
            "requires"
        },
        &unit_name,
    )?;

    if option_set.contains(&"x-systemd.automount") || option_set.contains(&"x-rustd.automount") {
        // Automount units are not started by the manager yet. Prefer a normal
        // local-fs mount rather than emitting a unit that can never activate.
        eprintln!(
            "rustd-fstab-generator: ignoring automount option for {where_}; mounting eagerly"
        );
    }
    Ok(())
}

fn write_swap(output: &Path, what: &str, options: &str, option_set: &[&str]) -> anyhow::Result<()> {
    let unit_name = path_unit_name(what, ".swap")?;
    let mut unit = format!(
        "# Generated by rustd-fstab-generator\n\
         [Unit]\nSourcePath=/etc/fstab\nBefore=swap.target\n\n\
         [Swap]\nWhat={what}\n"
    );
    let filtered = filtered_options(options);
    if !filtered.is_empty() && filtered != "defaults" {
        let _ = writeln!(unit, "Options={filtered}");
    }
    fs::write(output.join(&unit_name), unit)?;
    link_dependency(
        output,
        "swap.target",
        if option_set.contains(&"nofail") {
            "wants"
        } else {
            "requires"
        },
        &unit_name,
    )
}

fn link_dependency(output: &Path, target: &str, kind: &str, unit: &str) -> anyhow::Result<()> {
    let directory = output.join(format!("{target}.{kind}"));
    fs::create_dir_all(&directory)?;
    let link = directory.join(unit);
    if link.exists() {
        fs::remove_file(&link)?;
    }
    symlink(Path::new("..").join(unit), link)?;
    Ok(())
}

fn filtered_options(options: &str) -> String {
    options
        .split(',')
        .filter(|option| {
            !matches!(
                *option,
                "noauto" | "nofail" | "_netdev" | "x-systemd.automount"
            ) && !option.starts_with("x-systemd.")
        })
        .collect::<Vec<_>>()
        .join(",")
}

fn unescape_fstab(value: &str) -> String {
    value
        .replace("\\040", " ")
        .replace("\\011", "\t")
        .replace("\\134", "\\")
        .replace("\\043", "#")
}

fn path_unit_name(path: &str, suffix: &str) -> anyhow::Result<String> {
    if !path.starts_with('/') {
        return Err(anyhow!("fstab path is not absolute: {path}"));
    }
    if path == "/" {
        return Ok(format!("-{suffix}"));
    }
    let mut name = String::new();
    for byte in path
        .trim_end_matches('/')
        .as_bytes()
        .iter()
        .copied()
        .skip(1)
    {
        match byte {
            b'/' => name.push('-'),
            b'-' => name.push_str("\\x2d"),
            b'A'..=b'Z' | b'a'..=b'z' | b'0'..=b'9' | b':' | b'_' | b'.' => {
                name.push(char::from(byte));
            }
            _ => {
                let _ = write!(name, "\\x{byte:02x}");
            }
        }
    }
    name.push_str(suffix);
    Ok(name)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generates_mount_swap_and_dependencies() {
        let root = tempfile::tempdir().unwrap();
        let fstab = root.path().join("fstab");
        fs::write(
            &fstab,
            "UUID=data /srv/data ext4 defaults 0 2\n/swapfile none swap defaults 0 0\n",
        )
        .unwrap();
        let output = root.path().join("generator");
        generate_fstab(&fstab, &output).unwrap();

        assert!(output.join("srv-data.mount").is_file());
        assert!(output.join("swapfile.swap").is_file());
        assert!(output
            .join("local-fs.target.requires/srv-data.mount")
            .is_symlink());
        assert!(output
            .join("swap.target.requires/swapfile.swap")
            .is_symlink());
    }

    #[test]
    fn noauto_is_not_generated_and_nofail_is_wanted() {
        let root = tempfile::tempdir().unwrap();
        let fstab = root.path().join("fstab");
        fs::write(
            &fstab,
            "/dev/a /skip ext4 noauto 0 0\n/dev/b /optional ext4 nofail 0 0\n",
        )
        .unwrap();
        let output = root.path().join("generator");
        generate_fstab(&fstab, &output).unwrap();

        assert!(!output.join("skip.mount").exists());
        assert!(output
            .join("local-fs.target.wants/optional.mount")
            .is_symlink());
    }
}

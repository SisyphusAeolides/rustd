//! Generate native `RustD` mount/swap units from `/etc/fstab`.

use std::fmt::Write as _;
use std::fs;
use std::os::unix::fs::symlink;
use std::path::{Path, PathBuf};

use anyhow::{anyhow, Context};

fn main() {
    if let Err(error) = run() {
        eprintln!("rustd-fstab-generator: {error:#}");
        std::process::exit(1);
    }
}

fn run() -> anyhow::Result<()> {
    let args: Vec<PathBuf> = std::env::args_os().skip(1).map(PathBuf::from).collect();
    let normal = match args.as_slice() {
        [normal] | [_, normal, _] => normal,
        _ => {
            return Err(anyhow!(
                "expected one or three generator output directories"
            ))
        }
    };
    generate_fstab(Path::new("/etc/fstab"), normal)
}

fn generate_fstab(fstab: &Path, output: &Path) -> anyhow::Result<()> {
    let text = match fs::read_to_string(fstab) {
        Ok(text) => text,
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => return Ok(()),
        Err(error) => return Err(error).with_context(|| format!("read {}", fstab.display())),
    };
    fs::create_dir_all(output)?;

    let mut entries = Vec::new();
    for (line_number, raw) in text.lines().enumerate() {
        let line = raw.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let fields: Vec<String> = line.split_whitespace().map(unescape_fstab).collect();
        if fields.len() < 4 {
            return Err(anyhow!(
                "{}:{}: expected at least four fields",
                fstab.display(),
                line_number + 1
            ));
        }
        let what = &fields[0];
        let where_ = &fields[1];
        let fstype = &fields[2];
        let options = &fields[3];
        let option_set: Vec<&str> = options.split(',').collect();
        if option_set.contains(&"noauto") {
            continue;
        }

        entries.push((
            what.clone(),
            where_.clone(),
            fstype.clone(),
            options.clone(),
        ));
    }

    let mount_points: Vec<String> = entries
        .iter()
        .filter(|(_, where_, fstype, options)| {
            fstype != "swap" && where_ != "/" && !options.split(',').any(|item| item == "noauto")
        })
        .map(|(_, where_, _, _)| where_.clone())
        .collect();

    for (what, where_, fstype, options) in entries {
        let option_set: Vec<&str> = options.split(',').collect();
        if option_set.contains(&"noauto") {
            continue;
        }
        if fstype == "swap" {
            write_swap(output, &what, &options, &option_set)?;
        } else if where_ != "/" {
            let parent = nearest_parent_mount(&where_, &mount_points);
            write_mount(
                output,
                &what,
                &where_,
                &fstype,
                &options,
                &option_set,
                parent,
            )?;
        }
    }
    Ok(())
}

fn write_mount(
    output: &Path,
    what: &str,
    where_: &str,
    fstype: &str,
    options: &str,
    option_set: &[&str],
    parent_mount: Option<&str>,
) -> anyhow::Result<()> {
    let unit_name = path_unit_name(where_, ".mount")?;
    // Keep the generated unit equivalent to systemd-fstab-generator: device
    // identifiers are converted to the stable udev namespace before the
    // mount job is queued. The filesystem activator still validates and
    // canonicalizes the path when it runs.
    let source = fstab_source_path(what);
    let filtered = filtered_options(options);
    let remote = option_set.contains(&"_netdev");
    let mut after = Vec::new();
    if !remote && is_device_backed(what) {
        after.push("rustd-udev-settle.service".to_owned());
    }
    if let Some(parent) = parent_mount {
        after.push(path_unit_name(parent, ".mount")?);
    }
    let after_line = if after.is_empty() {
        String::new()
    } else {
        format!("After={}\n", after.join(" "))
    };
    let mut unit = format!(
        "# Generated by rustd-fstab-generator\n\
         [Unit]\nSourcePath=/etc/fstab\nBefore=local-fs.target\n\n\
         {after_line}\
         [Mount]\nWhat={source}\nWhere={where_}\n"
    );
    if fstype != "auto" {
        let _ = writeln!(unit, "Type={fstype}");
    }
    if !filtered.is_empty() && filtered != "defaults" {
        let _ = writeln!(unit, "Options={filtered}");
    }
    fs::write(output.join(&unit_name), unit)?;
    link_dependency(
        output,
        if option_set.contains(&"_netdev") {
            "remote-fs.target"
        } else {
            "local-fs.target"
        },
        if option_set.contains(&"nofail") {
            "wants"
        } else {
            "requires"
        },
        &unit_name,
    )?;

    if option_set.contains(&"x-systemd.automount") || option_set.contains(&"x-rustd.automount") {
        // Automount units are not started by the manager yet. Prefer a normal
        // local-fs mount rather than emitting a unit that can never activate.
        eprintln!(
            "rustd-fstab-generator: ignoring automount option for {where_}; mounting eagerly"
        );
    }
    Ok(())
}

fn is_device_backed(what: &str) -> bool {
    what.starts_with("/dev/")
        || ["UUID=", "LABEL=", "PARTUUID=", "PARTLABEL="]
            .iter()
            .any(|prefix| what.starts_with(prefix))
}

fn nearest_parent_mount<'a>(where_: &str, mount_points: &'a [String]) -> Option<&'a str> {
    mount_points
        .iter()
        .map(String::as_str)
        .filter(|candidate| {
            *candidate != where_
                && where_.starts_with(*candidate)
                && where_.as_bytes().get(candidate.len()) == Some(&b'/')
        })
        .max_by_key(|candidate| candidate.len())
}

fn write_swap(output: &Path, what: &str, options: &str, option_set: &[&str]) -> anyhow::Result<()> {
    let source = fstab_source_path(what);
    let unit_name = source_unit_name(&source, ".swap")?;
    let mut unit = format!(
        "# Generated by rustd-fstab-generator\n\
         [Unit]\nSourcePath=/etc/fstab\nBefore=swap.target\n\n\
         [Swap]\nWhat={source}\n"
    );
    let filtered = filtered_options(options);
    if !filtered.is_empty() && filtered != "defaults" {
        let _ = writeln!(unit, "Options={filtered}");
    }
    fs::write(output.join(&unit_name), unit)?;
    link_dependency(
        output,
        "swap.target",
        if option_set.contains(&"nofail") {
            "wants"
        } else {
            "requires"
        },
        &unit_name,
    )
}

fn link_dependency(output: &Path, target: &str, kind: &str, unit: &str) -> anyhow::Result<()> {
    let directory = output.join(format!("{target}.{kind}"));
    fs::create_dir_all(&directory)?;
    let link = directory.join(unit);
    if link.exists() {
        fs::remove_file(&link)?;
    }
    symlink(Path::new("..").join(unit), link)?;
    Ok(())
}

fn filtered_options(options: &str) -> String {
    options
        .split(',')
        .filter(|option| {
            !matches!(
                *option,
                "noauto" | "nofail" | "_netdev" | "x-systemd.automount"
            ) && !option.starts_with("x-systemd.")
        })
        .collect::<Vec<_>>()
        .join(",")
}

fn unescape_fstab(value: &str) -> String {
    value
        .replace("\\040", " ")
        .replace("\\011", "\t")
        .replace("\\134", "\\")
        .replace("\\043", "#")
}

/// Resolve an fstab device identifier to the stable `/dev/disk` path used by
/// native mount and swap units. Mount units resolve these identifiers when
/// they activate; swap units need the normalized path up front because the
/// Linux `swapon(2)` call does not understand `UUID=` or `LABEL=` strings.
fn fstab_source_path(source: &str) -> String {
    let Some((kind, value)) = source.split_once('=') else {
        return source.to_owned();
    };
    let directory = match kind {
        "UUID" => "uuid",
        "LABEL" => "label",
        "PARTUUID" => "partuuid",
        "PARTLABEL" => "partlabel",
        _ => return source.to_owned(),
    };
    if value.is_empty() {
        source.to_owned()
    } else {
        format!("/dev/disk/by-{directory}/{value}")
    }
}

/// Name a generated unit from either an absolute source path or a legacy
/// non-path fstab token. Invalid source tokens must not abort PID1 startup;
/// they become a unit which can report its own activation failure instead.
fn source_unit_name(source: &str, suffix: &str) -> anyhow::Result<String> {
    if source.starts_with('/') {
        return path_unit_name(source, suffix);
    }
    let mut name = String::from("source-");
    for byte in source.as_bytes().iter().copied() {
        match byte {
            b'A'..=b'Z' | b'a'..=b'z' | b'0'..=b'9' | b':' | b'_' | b'.' => {
                name.push(char::from(byte));
            }
            _ => {
                let _ = write!(name, "\\x{byte:02x}");
            }
        }
    }
    name.push_str(suffix);
    Ok(name)
}

fn path_unit_name(path: &str, suffix: &str) -> anyhow::Result<String> {
    if !path.starts_with('/') {
        return Err(anyhow!("fstab path is not absolute: {path}"));
    }
    if path == "/" {
        return Ok(format!("-{suffix}"));
    }
    let mut name = String::new();
    for byte in path
        .trim_end_matches('/')
        .as_bytes()
        .iter()
        .copied()
        .skip(1)
    {
        match byte {
            b'/' => name.push('-'),
            b'-' => name.push_str("\\x2d"),
            b'A'..=b'Z' | b'a'..=b'z' | b'0'..=b'9' | b':' | b'_' | b'.' => {
                name.push(char::from(byte));
            }
            _ => {
                let _ = write!(name, "\\x{byte:02x}");
            }
        }
    }
    name.push_str(suffix);
    Ok(name)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generates_mount_swap_and_dependencies() {
        let root = tempfile::tempdir().unwrap();
        let fstab = root.path().join("fstab");
        fs::write(
            &fstab,
            "UUID=data /srv/data ext4 defaults 0 2\n/swapfile none swap defaults 0 0\n",
        )
        .unwrap();
        let output = root.path().join("generator");
        generate_fstab(&fstab, &output).unwrap();

        assert!(output.join("srv-data.mount").is_file());
        assert!(fs::read_to_string(output.join("srv-data.mount"))
            .unwrap()
            .contains("After=rustd-udev-settle.service"));
        assert!(fs::read_to_string(output.join("srv-data.mount"))
            .unwrap()
            .contains("What=/dev/disk/by-uuid/data"));
        assert!(output.join("swapfile.swap").is_file());
        assert!(output
            .join("local-fs.target.requires/srv-data.mount")
            .is_symlink());
        assert!(output
            .join("swap.target.requires/swapfile.swap")
            .is_symlink());
    }

    #[test]
    fn normalizes_swap_device_identifiers() {
        let root = tempfile::tempdir().unwrap();
        let fstab = root.path().join("fstab");
        fs::write(
            &fstab,
            "UUID=01234567-89ab-cdef-0123-456789abcdef none swap defaults 0 0\n",
        )
        .unwrap();
        let output = root.path().join("generator");
        generate_fstab(&fstab, &output).unwrap();

        let unit_name =
            "dev-disk-by\\x2duuid-01234567\\x2d89ab\\x2dcdef\\x2d0123\\x2d456789abcdef.swap";
        let unit = output.join(unit_name);
        assert!(unit.is_file());
        assert!(fs::read_to_string(&unit)
            .unwrap()
            .contains("What=/dev/disk/by-uuid/01234567-89ab-cdef-0123-456789abcdef"));
    }

    #[test]
    fn device_mounts_wait_for_udev_and_nested_mounts_wait_for_parents() {
        let root = tempfile::tempdir().unwrap();
        let fstab = root.path().join("fstab");
        fs::write(
            &fstab,
            "UUID=boot /boot ext4 defaults 0 2\nUUID=efi /boot/efi vfat defaults 0 2\ntmpfs /run/cache tmpfs defaults 0 0\n",
        )
        .unwrap();
        let output = root.path().join("generator");
        generate_fstab(&fstab, &output).unwrap();

        let boot = fs::read_to_string(output.join("boot.mount")).unwrap();
        assert!(boot.contains("After=rustd-udev-settle.service"));
        let efi = fs::read_to_string(output.join("boot-efi.mount")).unwrap();
        assert!(efi.contains("After=rustd-udev-settle.service boot.mount"));
        let cache = fs::read_to_string(output.join("run-cache.mount")).unwrap();
        assert!(!cache.contains("rustd-udev-settle.service"));
    }

    #[test]
    fn noauto_is_not_generated_and_nofail_is_wanted() {
        let root = tempfile::tempdir().unwrap();
        let fstab = root.path().join("fstab");
        fs::write(
            &fstab,
            "/dev/a /skip ext4 noauto 0 0\n/dev/b /optional ext4 nofail 0 0\n",
        )
        .unwrap();
        let output = root.path().join("generator");
        generate_fstab(&fstab, &output).unwrap();

        assert!(!output.join("skip.mount").exists());
        assert!(output
            .join("local-fs.target.wants/optional.mount")
            .is_symlink());
    }
}
